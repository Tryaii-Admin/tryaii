#!/usr/bin/env python
"""Freeze the fp32 classification of the parity prompts (TS-252).

Writes shared/catalog/parity/embedding_parity.json: for every prompt of the
monitor fixture corpus (the routing texts of shared/monitor/fixtures/extract)
and of the catalog parity set (shared/catalog/parity/starter_prompts.json),
its similarity to each starter benchmark centroid with the fp32 model
(sentence-transformers all-MiniLM-L6-v2 + centroids.json).

packages/python/tests/test_embedding_parity.py classifies the same prompts
with the int8 ONNX build (+ its own centroids) and checks the top benchmark
is identical, allowing the top two to swap only where both builds put them
less than 0.01 apart. The frozen fp32 side lets that test run without
PyTorch; when sentence-transformers is installed the test also re-checks
this file against a live fp32 run.

Requires the ``centroids`` extra (sentence-transformers).

Usage:
  python scripts/gen-embedding-parity.py           # write
  python scripts/gen-embedding-parity.py --check   # exit 1 on drift
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "packages" / "python"))

OUT = REPO / "shared" / "catalog" / "parity" / "embedding_parity.json"
EXTRACT = REPO / "shared" / "monitor" / "fixtures" / "extract" / "cases.json"
CATALOG_PROMPTS = REPO / "shared" / "catalog" / "parity" / "starter_prompts.json"
FP32_MODEL = "all-MiniLM-L6-v2"
INT8_MODEL = "all-MiniLM-L6-v2-onnx-int8"
DECIMALS = 6


def parity_prompts() -> list[dict]:
    """``[{"source", "prompt"}]``: the fixture corpus first, then the catalog set."""
    out = []
    for case in json.loads(EXTRACT.read_text(encoding="utf-8"))["cases"]:
        text = case["expected"]["text"]
        if text:
            out.append({"source": f"monitor/extract/{case['name']}", "prompt": text})
    for entry in json.loads(CATALOG_PROMPTS.read_text(encoding="utf-8"))["prompts"]:
        out.append({"source": "catalog/starter_prompts", "prompt": entry["prompt"]})
    return out


def fp32_similarities(prompts: list[str]) -> list[dict]:
    import numpy as np
    from tryaii.catalog.bundle import starter_bundle
    from tryaii.embeddings.sentence_transformers_provider import (
        SentenceTransformerEmbeddingProvider,
    )

    centroids = starter_bundle().centroids_for(FP32_MODEL)["centroids"]
    names = sorted(centroids)
    matrix = np.array([centroids[n] for n in names], dtype=np.float32)
    provider = SentenceTransformerEmbeddingProvider(FP32_MODEL, device="cpu")
    vectors = np.stack(provider.embed_batch(prompts))
    sims = vectors @ matrix.T / np.linalg.norm(matrix, axis=1)
    return [{name: round(max(0.0, float(v)), DECIMALS) for name, v in zip(names, row)}
            for row in sims]


def build() -> str:
    from tryaii.catalog.bundle import starter_bundle

    entries = parity_prompts()
    sims = fp32_similarities([e["prompt"] for e in entries])
    doc = {
        "description": "fp32 (sentence-transformers all-MiniLM-L6-v2) similarities of the "
                       "parity prompts to the starter centroids; generated by "
                       "scripts/gen-embedding-parity.py, compared with the int8 ONNX build "
                       "by tests/test_embedding_parity.py (TS-252).",
        "starter_version": starter_bundle().version,
        "fp32_model": FP32_MODEL,
        "int8_model": INT8_MODEL,
        "prompts": [{**e, "fp32_similarities": s} for e, s in zip(entries, sims)],
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = build()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    if args.check:
        if current != text:
            print(f"DRIFT in {OUT.relative_to(REPO)}")
            return 1
        print("embedding parity file up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    count = len(json.loads(text)["prompts"])
    print(f"wrote {OUT.relative_to(REPO)} ({count} prompts)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
