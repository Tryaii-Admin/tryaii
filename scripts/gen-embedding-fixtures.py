#!/usr/bin/env python
"""Freeze the int8 ONNX embedding model's tokenizer ids and classifications (TS-253).

Writes two files the Node SDK must reproduce:

shared/embeddings/tokenizer_parity.json: the token ids the Python SDK feeds
the model (tryaii.embeddings.onnx_provider: tokenizer.json, truncation to 256
tokens including [CLS]/[SEP], no padding) for the monitor fixture corpus
prompts, every starter training query and a set of Unicode edge cases. The
Node tokenizer (packages/node/src/embeddings/wordpiece.ts) must produce
exactly these ids (packages/node/tests/wordpiece.test.ts).

shared/embeddings/classification_parity.json: for the monitor fixture corpus
prompts and the catalog parity prompts, the Python classification with the
int8 model and its own starter centroids (similarity to every benchmark, 6
decimals; category; subcategory). Node must give the same category and
similarities within 5e-5 (packages/node/tests/embedding-parity.test.ts).
This one needs the real model file (the tryaii-minilm-int8 package or
TRYAII_EMBEDDING_MODEL_PATH).

Usage:
  python scripts/gen-embedding-fixtures.py           # write
  python scripts/gen-embedding-fixtures.py --check   # exit 1 on drift
"""
from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "packages" / "python"))

MODEL = "all-MiniLM-L6-v2-onnx-int8"
OUT_TOKENIZER = REPO / "shared" / "embeddings" / "tokenizer_parity.json"
OUT_CLASSIFICATION = REPO / "shared" / "embeddings" / "classification_parity.json"
EXTRACT = REPO / "shared" / "monitor" / "fixtures" / "extract" / "cases.json"
CATALOG_PROMPTS = REPO / "shared" / "catalog" / "parity" / "starter_prompts.json"

EDGE_CASES = [
    "",
    "   ",
    "Héllo Wörld, naïve café — résumé!",
    "ÀÉÎÕÜ ñ ç ß ø å æ œ",
    "ΣΟΦΟΣ σοφος ΟΔΥΣΣΕΥΣ",
    "İstanbul ışık",
    "中文分词测试，标点符号。",
    "日本語のテキストとカタカナ",
    "한국어 텍스트",
    "עברית: תרגם את המשפט הזה",
    "العربية نص تجريبي",
    "emoji 🚀🔥 and ☕ coffee 👩‍💻",
    "tabs\tand\nnewlines\r\nand nbsp em-space",
    "zero​width‍joiner﻿bom",
    "control\u0001chars\u007fhere�replacement",
    "x" * 150,
    "supercalifragilisticexpialidocious antidisestablishmentarianism",
    "C++ / C# / F#: a->b, x<=y, {k: v}, [1, 2], (a|b) & !c ~ ^ `code` $100 50% @user #tag",
    "unbelievable unaffordable reconnect preprocessing tokenization",
    "Write a Python function that merges two sorted lists. " * 40,
]


def _corpus() -> list[dict]:
    return [{"source": f"monitor/extract/{case['name']}", "text": case["expected"]["text"]}
            for case in json.loads(EXTRACT.read_text(encoding="utf-8"))["cases"]]


def tokenizer_texts() -> list[dict]:
    from tryaii.catalog.bundle import starter_bundle

    out = _corpus()
    for name, queries in starter_bundle().training_query_map().items():
        for i, q in enumerate(queries):
            out.append({"source": f"starter/{name}/{i}", "text": q})
    for i, t in enumerate(EDGE_CASES):
        out.append({"source": f"edge/{i}", "text": t})
    return out


def classification_prompts() -> list[dict]:
    out = [c for c in _corpus() if c["text"]]
    for entry in json.loads(CATALOG_PROMPTS.read_text(encoding="utf-8"))["prompts"]:
        out.append({"source": "catalog/starter_prompts", "text": entry["prompt"]})
    return out


def build_tokenizer() -> str:
    from tokenizers import Tokenizer
    from tryaii.embeddings.model_store import MODELS, tokenizer_path

    tok = Tokenizer.from_file(str(tokenizer_path(MODEL)))
    tok.enable_truncation(max_length=MODELS[MODEL].max_length)
    tok.enable_padding(pad_id=0, pad_token="[PAD]")   # as the provider; one text = no padding
    rows = [{**t, "ids": tok.encode(t["text"]).ids} for t in tokenizer_texts()]
    doc = {
        "description": "Token ids of the int8 ONNX embedding model's tokenizer as the Python SDK "
                       "runs it (truncation 256 incl. [CLS]/[SEP], no padding); generated by "
                       "scripts/gen-embedding-fixtures.py. The Node tokenizer must match (TS-253).",
        "model": MODEL,
        "max_length": MODELS[MODEL].max_length,
        "cases": rows,
    }
    return json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + "\n"


def build_classification() -> str:
    from tryaii.catalog.bundle import starter_bundle
    from tryaii.centroids.loader import CentroidLoader
    from tryaii.classifiers.embedding import EmbeddingClassifier
    from tryaii.config import TryaiiDreConfig
    from tryaii.embeddings.onnx_provider import OnnxEmbeddingProvider

    provider = OnnxEmbeddingProvider(MODEL)
    config = TryaiiDreConfig(embedding_model=MODEL, data_dir=tempfile.mkdtemp())
    bundle = starter_bundle()
    classifier = EmbeddingClassifier(provider, CentroidLoader(config, provider, bundle=bundle),
                                     config)
    rows = []
    for p in classification_prompts():
        r = classifier.classify(p["text"])
        sims = {k: round(v, 6) for k, v in sorted(r.benchmark_scores.items())}
        rows.append({**p, "category": r.broad_category, "subcategory": r.subcategory,
                     "similarities": sims})
    doc = {
        "description": "Python classification of the parity prompts with the int8 ONNX model and "
                       "its own starter centroids; generated by "
                       "scripts/gen-embedding-fixtures.py. The "
                       "Node SDK must match: same category, similarities within 5e-5 (TS-253).",
        "model": MODEL,
        "starter_version": bundle.version,
        "cases": rows,
    }
    return json.dumps(doc, ensure_ascii=False, indent=1) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    outputs = {OUT_TOKENIZER: build_tokenizer(), OUT_CLASSIFICATION: build_classification()}
    drift = []
    for path, text in outputs.items():
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != text:
                drift.append(str(path.relative_to(REPO)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(REPO)} ({len(json.loads(text)['cases'])} cases)")
    if args.check:
        if drift:
            print("DRIFT in:", *drift, sep="\n  ")
            return 1
        print("embedding fixtures up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
