/**
 * SentencePiece Unigram tokenizer, id-for-id the one the Python SDK runs
 * (HF `tokenizers` 0.23, Rust), read from the same `tokenizer.json`. No
 * dependencies. Used by the H4 router (packages/router-h4-model).
 *
 * Parity with the Python ids is frozen by shared/embeddings/unigram_parity.json
 * (scripts/gen-unigram-fixture.py; packages/node/tests/unigram.test.ts).
 *
 * Pipeline, as in `tokenizers::Tokenizer::encode(text, add_special_tokens)`:
 * 1. added tokens (here `[PAD]`, `[UNK]`, normalized=false) are matched on the
 *    raw text, leftmost-longest; each one is its own id, and the text between
 *    them is processed segment by segment (steps 2-4);
 * 2. normalizer: Sequence / Replace (String or Regex) / NFKC / Strip;
 * 3. pre-tokenizer Metaspace: ' ' -> '▁', prepend '▁' unless the segment
 *    already starts with it (prepend_scheme "always"), no split;
 * 4. Unigram Viterbi over code points (see `viterbi`).
 * Post-processor: TemplateProcessing "$A" only (adds nothing).
 *
 * Anything else in the file (other normalizer / pre-tokenizer / model types,
 * byte fallback, normalized added tokens, ...) is rejected with an
 * `UnigramTokenizerError` (code "unsupported"): fail closed, never guess.
 *
 * Unicode notes:
 * - JS strings are UTF-16; Rust works on code points. Lone surrogates (which
 *   Python/Rust cannot even receive) are replaced with U+FFFD first.
 * - Rust NFKC (crate unicode-normalization-alignments) uses old Unicode
 *   tables (about Unicode 9); Node's ICU is newer. The code points listed in
 *   `NFKC_GUARD` are passed through NFKC untouched, which reproduces the Rust
 *   result exactly (verified for every assigned code point with combining
 *   contexts); see `nfkc`.
 * - Regex `\s` (Oniguruma) and Strip (Rust char::is_whitespace) both use the
 *   Unicode White_Space set, which differs from JS `\s` (JS adds U+FEFF and
 *   lacks U+0085), so it is spelled out in `WS_CLASS`.
 */

export type UnigramErrorCode = 'malformed' | 'unsupported';

/** Thrown when a tokenizer.json is malformed or uses an unsupported feature. */
export class UnigramTokenizerError extends Error {
  readonly code: UnigramErrorCode;

  constructor(code: UnigramErrorCode, message: string) {
    super(`tokenizer.json ${code}: ${message}`);
    this.name = 'UnigramTokenizerError';
    this.code = code;
  }
}

export interface UnigramOptions {
  /**
   * Inputs longer than this many UTF-16 code units are cut (at a code point
   * boundary) before tokenization, so a huge input cannot cost unbounded time
   * or memory. Default 100 000; the H4 provider caps at 3 500 code points
   * before it calls the tokenizer anyway.
   */
  maxInputLength?: number;
}

