function buildGuard(): RegExp {
  const parts = NFKC_GUARD_RANGES.split(',').map((r) => {
    const [a, b] = r.split('-');
    return b === undefined ? `\\u{${a}}` : `\\u{${a}}-\\u{${b}}`;
  });
  return new RegExp(`[${parts.join('')}]+`, 'gu');
}

const RE_NFKC_GUARD = buildGuard();

/** NFKC as Rust's unicode-normalization-alignments computes it. */
export function nfkc(text: string): string {
  RE_NFKC_GUARD.lastIndex = 0;
  if (!RE_NFKC_GUARD.test(text)) return text.normalize('NFKC');
  // Guarded code points act as starters with no decomposition (what an
  // unknown code point is to Rust), so normalizing the runs between them on
  // their own is exact.
  RE_NFKC_GUARD.lastIndex = 0;
  let out = '';
  let last = 0;
  let m: RegExpExecArray | null;
  while ((m = RE_NFKC_GUARD.exec(text)) !== null) {
    out += text.slice(last, m.index).normalize('NFKC') + m[0];
    last = m.index + m[0].length;
  }
  return out + text.slice(last).normalize('NFKC');
}

type Step = (s: string) => string;

function fail(code: UnigramErrorCode, message: string): never {
  throw new UnigramTokenizerError(code, message);
}

function isObject(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

function escapeCodePoint(ch: string): string {
  return `\\u{${(ch.codePointAt(0) as number).toString(16)}}`;
}

/**
 * Translates the Oniguruma regexes a tokenizer.json may hold into JS. Only a
 * safe subset is accepted (fail closed): literal characters, `\s`, character
 * classes of literal characters and ranges, and the quantifiers + * ? {n,m}.
 */
export function translateRegex(pattern: string): string {
  const chars = Array.from(pattern);
  let out = '';
  let i = 0;
  const bad = (why: string): never => fail('unsupported', `regex ${JSON.stringify(pattern)}: ${why}`);
  while (i < chars.length) {
    const ch = chars[i];
    if (ch === '\\') {
      if (chars[i + 1] === 's') {
        out += `[${WS_CLASS}]`;
        i += 2;
        continue;
      }
      bad('only the \\s escape is supported');
    }
    if (ch === '[') {
      let j = i + 1;
      if (chars[j] === '^') bad('negated classes are not supported');
      let cls = '';
      let n = 0;
      while (j < chars.length && chars[j] !== ']') {
        const c = chars[j];
        if (c === '\\' || c === '[') bad('escapes and nested classes inside [] are not supported');
        if (c === '-' && n > 0 && j + 1 < chars.length && chars[j + 1] !== ']') {
          const hi = chars[j + 1];
          if (hi === '\\' || hi === '[') bad('unsupported range end');
          cls += `-${escapeCodePoint(hi)}`;
          j += 2;
          n += 1;
          continue;
        }
        cls += escapeCodePoint(c);
        j += 1;
        n += 1;
      }
      if (j >= chars.length || n === 0) bad('unterminated or empty class');
      out += `[${cls}]`;
      i = j + 1;
      continue;
    }
    if (ch === '+' || ch === '*' || ch === '?') {
      if (out === '') bad('quantifier without operand');
      out += ch;
      i += 1;
      continue;
    }
    if (ch === '{') {
      const rest = chars.slice(i).join('');
      const q = /^\{\d+(,\d*)?\}/.exec(rest);
      if (!q || out === '') bad('unsupported brace');
      out += (q as RegExpExecArray)[0];
      i += Array.from((q as RegExpExecArray)[0]).length;
      continue;
    }
    if ('().|^$]}'.includes(ch)) bad(`metacharacter ${JSON.stringify(ch)} is not supported`);
    out += escapeCodePoint(ch);
    i += 1;
  }
  if (out === '') bad('empty pattern');
  return out;
}

function compileNormalizer(spec: unknown, out: Step[], path: string): void {
  if (!isObject(spec)) fail('malformed', `${path} is not an object`);
  const type = spec.type;
  switch (type) {
    case 'Sequence': {
      if (!Array.isArray(spec.normalizers)) fail('malformed', `${path}.normalizers is not an array`);
      spec.normalizers.forEach((n, i) => compileNormalizer(n, out, `${path}.normalizers[${i}]`));
      return;
    }
    case 'NFKC':
      out.push(nfkc);
      return;
    case 'Strip': {
      const left = spec.strip_left;
      const right = spec.strip_right;
      if (typeof left !== 'boolean' || typeof right !== 'boolean') {
        fail('malformed', `${path}: Strip needs boolean strip_left/strip_right`);
      }
      out.push((s) => {
        let r = s;
        if (left) r = r.replace(RE_WS_START, '');
        if (right) r = r.replace(RE_WS_END, '');
        return r;
      });
      return;
    }
    case 'Replace': {
      const pattern = spec.pattern;
      const content = spec.content;
      if (!isObject(pattern) || typeof content !== 'string') {
        fail('malformed', `${path}: Replace needs pattern and content`);
      }
      if (typeof pattern.String === 'string' && pattern.Regex === undefined) {
        const needle = pattern.String;
        if (needle === '') fail('unsupported', `${path}: empty String pattern`);
        out.push((s) => (s.includes(needle) ? s.split(needle).join(content) : s));
        return;
      }
      if (typeof pattern.Regex === 'string' && pattern.String === undefined) {
        const source = translateRegex(pattern.Regex);
        if (new RegExp(`^(?:${source})$`, 'u').test('')) {
          fail('unsupported', `${path}: regex can match the empty string`);
        }
        const re = new RegExp(source, 'gu');
        // A function replacer: content is literal (no $-substitution), as in Rust.
        out.push((s) => s.replace(re, () => content));
        return;
      }
      fail('malformed', `${path}: Replace pattern must be {String} or {Regex}`);
    }
    // falls through (unreachable: fail() throws)
    default:
      fail('unsupported', `${path}: normalizer type ${JSON.stringify(type)}`);
  }
}

interface AddedToken {
  id: number;
  content: string;
}

function escapeRegexLiteral(s: string): string {
  return Array.from(s).map(escapeCodePoint).join('');
}

const MAX_CP = 0x110000;

export class UnigramTokenizer {
  /** Truncation max_length from the file (not applied by encode), or null. */
  readonly maxLength: number | null;
  readonly unkId: number | null;
  readonly vocabSize: number;
  private readonly maxInputLength: number;
  private readonly normalizers: Step[];
  private readonly replacement: string;
  private readonly prepend: boolean;
  private readonly addedRe: RegExp | null;
  private readonly added: Map<string, number>;
  private readonly pieceToId: Map<string, number>;
  private readonly scores: Float64Array;
  /** Trie transitions: key node * 0x110000 + code point -> child node. */
  private readonly edges: Map<number, number>;
  /** Trie node -> piece id ending there, or -1. */
  private readonly nodePiece: Int32Array;
  private readonly unkScore: number;

  constructor(json: unknown, options: UnigramOptions = {}) {
    if (!isObject(json)) fail('malformed', 'top level is not an object');
    const maxInput = options.maxInputLength ?? 100_000;
    if (!Number.isInteger(maxInput) || maxInput < 1) throw new RangeError('maxInputLength must be a positive integer');
    this.maxInputLength = maxInput;

    // --- model ---
    const model = json.model;
    if (!isObject(model)) fail('malformed', 'model is missing');
    if (model.type !== 'Unigram') fail('unsupported', `model type ${JSON.stringify(model.type)}`);
    if (model.byte_fallback !== undefined && model.byte_fallback !== false) {
      fail('unsupported', 'byte_fallback');
    }
    const vocab = model.vocab;
    if (!Array.isArray(vocab) || vocab.length === 0) fail('malformed', 'model.vocab must be a non-empty array');
    const n = vocab.length;
    this.vocabSize = n;
    this.scores = new Float64Array(n);
    this.pieceToId = new Map();
    this.edges = new Map();
    const nodePiece: number[] = [-1];
    let minScore = Infinity;
    for (let id = 0; id < n; id++) {
      const entry = vocab[id];
      if (!Array.isArray(entry) || entry.length !== 2 || typeof entry[0] !== 'string' ||
          typeof entry[1] !== 'number' || !Number.isFinite(entry[1])) {
        fail('malformed', `model.vocab[${id}] must be [piece, finite score]`);
      }
      const piece = entry[0] as string;
      const score = entry[1] as number;
      if (piece === '') fail('malformed', `model.vocab[${id}] is an empty piece`);
      if (RE_LONE_SURROGATE.test(piece)) {
        RE_LONE_SURROGATE.lastIndex = 0;
        fail('malformed', `model.vocab[${id}] has a lone surrogate`);
      }
      RE_LONE_SURROGATE.lastIndex = 0;
      this.scores[id] = score;
      if (score < minScore) minScore = score;
      this.pieceToId.set(piece, id); // later duplicates win, as in Rust
      let node = 0;
      for (const ch of piece) {
        const key = node * MAX_CP + (ch.codePointAt(0) as number);
        let next = this.edges.get(key);
        if (next === undefined) {
          next = nodePiece.length;
          nodePiece.push(-1);
          this.edges.set(key, next);
        }
        node = next;
      }
      nodePiece[node] = id;
    }
    // Repoint trie leaves at the winning id for duplicated pieces.
    for (let i = 0; i < nodePiece.length; i++) {
      if (nodePiece[i] >= 0) {
        const piece = (vocab[nodePiece[i]] as [string, number])[0];
        nodePiece[i] = this.pieceToId.get(piece) as number;
      }
    }
    this.nodePiece = Int32Array.from(nodePiece);
    this.unkScore = minScore - 10.0;
    const unk = model.unk_id;
    if (unk === undefined || unk === null) {
      this.unkId = null;
    } else {
      if (!Number.isInteger(unk) || (unk as number) < 0 || (unk as number) >= n) {
        fail('malformed', `model.unk_id ${JSON.stringify(unk)} out of range`);
      }
      this.unkId = unk as number;
    }

    // --- added tokens ---
    this.added = new Map();
    const addedTokens = json.added_tokens ?? [];
    if (!Array.isArray(addedTokens)) fail('malformed', 'added_tokens is not an array');
    const toks: AddedToken[] = [];
    addedTokens.forEach((t, i) => {
      if (!isObject(t) || typeof t.content !== 'string' || t.content === '' || !Number.isInteger(t.id)) {
        fail('malformed', `added_tokens[${i}]`);
      }
      if (t.normalized !== false) fail('unsupported', `added_tokens[${i}]: normalized added tokens`);
      if (t.lstrip === true || t.rstrip === true || t.single_word === true) {
        fail('unsupported', `added_tokens[${i}]: lstrip/rstrip/single_word`);
      }
      toks.push({ id: t.id as number, content: t.content as string });
      this.added.set(t.content as string, t.id as number);
    });
    // Leftmost-longest: alternation tries longer contents first.
    toks.sort((a, b) => b.content.length - a.content.length);
    this.addedRe = toks.length
      ? new RegExp(toks.map((t) => escapeRegexLiteral(t.content)).join('|'), 'gu')
      : null;

    // --- normalizer ---
    this.normalizers = [];
    if (json.normalizer !== null && json.normalizer !== undefined) {
      compileNormalizer(json.normalizer, this.normalizers, 'normalizer');
    }

    // --- pre-tokenizer ---
    const pre = json.pre_tokenizer;
    if (!isObject(pre)) fail('unsupported', 'pre_tokenizer must be Metaspace');
    if (pre.type !== 'Metaspace') fail('unsupported', `pre_tokenizer type ${JSON.stringify(pre.type)}`);
    if (typeof pre.replacement !== 'string' || Array.from(pre.replacement).length !== 1) {
      fail('malformed', 'Metaspace replacement must be one character');
    }
    if (pre.split !== false) fail('unsupported', 'Metaspace split=true');
    if (pre.prepend_scheme === 'always') this.prepend = true;
    else if (pre.prepend_scheme === 'never') this.prepend = false;
    else fail('unsupported', `Metaspace prepend_scheme ${JSON.stringify(pre.prepend_scheme)}`);
    this.replacement = pre.replacement as string;

    // --- post-processor ---
    const post = json.post_processor;
    if (post !== null && post !== undefined) {
      if (!isObject(post) || post.type !== 'TemplateProcessing') {
        fail('unsupported', 'post_processor must be null or TemplateProcessing');
      }
      const single = post.single;
      const ok = Array.isArray(single) && single.length === 1 && isObject(single[0]) &&
        isObject(single[0].Sequence) && single[0].Sequence.id === 'A';
      if (!ok) fail('unsupported', 'post_processor single template must be exactly $A');
      if (post.special_tokens !== undefined && !(isObject(post.special_tokens) &&
          Object.keys(post.special_tokens).length === 0)) {
        fail('unsupported', 'post_processor special tokens');
      }
    }

    const trunc = json.truncation;
    this.maxLength = isObject(trunc) && Number.isInteger(trunc.max_length) ? (trunc.max_length as number) : null;
  }

  /** Token ids of `text` (no truncation to maxLength). */
  encode(text: string): number[] {
    if (typeof text !== 'string') throw new TypeError('text must be a string');
    let s = text;
    if (s.length > this.maxInputLength) {
      let cut = this.maxInputLength;
      const c = s.charCodeAt(cut - 1);
      if (c >= 0xd800 && c <= 0xdbff) cut -= 1;
      s = s.slice(0, cut);
    }
    s = s.replace(RE_LONE_SURROGATE, '�');
    const ids: number[] = [];
    if (this.addedRe === null) {
      this.encodeSegment(s, ids);
      return ids;
    }
    const re = this.addedRe;
    re.lastIndex = 0;
    let last = 0;
    let m: RegExpExecArray | null;
    while ((m = re.exec(s)) !== null) {
      if (m.index > last) this.encodeSegment(s.slice(last, m.index), ids);
      ids.push(this.added.get(m[0]) as number);
      last = m.index + m[0].length;
    }
    if (last < s.length) this.encodeSegment(s.slice(last), ids);
    return ids;
  }

  private encodeSegment(segment: string, ids: number[]): void {
    let s = segment;
    for (const step of this.normalizers) s = step(s);
    if (s === '') return;
    const rep = this.replacement;
    if (s.includes(' ')) s = s.split(' ').join(rep);
    if (this.prepend && !s.startsWith(rep)) s = rep + s;
    this.viterbi(s, ids);
  }

  /**
   * Unigram::encode_optimized from tokenizers (Rust), on code points:
   * best[k] is the best path ending at code point k; every vocab piece that
   * starts at k (shortest first) relaxes best[k + len] when it is strictly
   * better (or the end is not yet reached); if no single-code-point piece
   * starts at k, an unknown piece of one code point with score
   * min(score) - 10 relaxes best[k + 1] the same way. Backtracking fuses
   * runs of consecutive unknowns into one token (fuse_unk), which then maps
   * to its vocab id if it is a piece, else unk_id.
   */
  private viterbi(s: string, ids: number[]): void {
    const cps: number[] = [];
    for (let i = 0; i < s.length; i++) {
      const c = s.charCodeAt(i);
      if (c >= 0xd800 && c <= 0xdbff && i + 1 < s.length) {
        const d = s.charCodeAt(i + 1);
        if (d >= 0xdc00 && d <= 0xdfff) {
          cps.push(((c - 0xd800) << 10) + (d - 0xdc00) + 0x10000);
          i++;
          continue;
        }
      }
      cps.push(c);
    }
    const size = cps.length;
    const score = new Float64Array(size + 1);
    const from = new Int32Array(size + 1).fill(-1);
    const tok = new Int32Array(size + 1);
    const edges = this.edges;
    const nodePiece = this.nodePiece;
    const scores = this.scores;
    const UNK = -1;
    for (let start = 0; start < size; start++) {
      const base = score[start];
      let single = false;
      let node = 0;
      for (let k = start; k < size; k++) {
        const next = edges.get(node * MAX_CP + cps[k]);
        if (next === undefined) break;
        node = next;
        const id = nodePiece[node];
        if (id < 0) continue;
        const end = k + 1;
        const cand = scores[id] + base;
        if (from[end] < 0 || cand > score[end]) {
          score[end] = cand;
          from[end] = start;
          tok[end] = id;
        }
        if (end === start + 1) single = true;
      }
      if (!single) {
        const end = start + 1;
        const cand = this.unkScore + base;
        if (from[end] < 0 || cand > score[end]) {
          score[end] = cand;
          from[end] = start;
          tok[end] = UNK;
        }
      }
    }
    // Backtrack. tok = UNK marks an unknown span (Rust stores unk_id there;
    // a real unk_id piece can never be chosen through the trie with the
    // tokenizers this SDK ships, but handle it the Rust way regardless).
    const out: number[] = [];
    let end = size;
    let unkEnd = -1;
    const flushUnk = (unkStart: number): void => {
      const text = String.fromCodePoint(...cps.slice(unkStart, unkEnd));
      const id = this.pieceToId.get(text);
      if (id !== undefined) out.push(id);
      else if (this.unkId !== null) out.push(this.unkId);
      else fail('unsupported', 'unknown token but model.unk_id is null');
      unkEnd = -1;
    };
    const unkId = this.unkId;
    let unkStart = -1;
    while (end > 0) {
      const start = from[end];
      const id = tok[end];
      const isUnk = id === UNK || (unkId !== null && id === unkId);
      if (isUnk) {
        if (unkEnd < 0) unkEnd = end;
        unkStart = start;
      } else {
        if (unkEnd >= 0) flushUnk(unkStart);
        out.push(id);
      }
      end = start;
    }
    if (unkEnd >= 0) flushUnk(unkStart);
    for (let i = out.length - 1; i >= 0; i--) ids.push(out[i]);
  }
}

/** First `n` code points of `text` (Python `text[:n]`). */
export function sliceCodePoints(text: string, n: number): string {
  if (text.length <= n) return text;
  let i = 0;
  let count = 0;
  while (i < text.length && count < n) {
    const c = text.charCodeAt(i);
    i += c >= 0xd800 && c <= 0xdbff && i + 1 < text.length &&
      (text.charCodeAt(i + 1) & 0xfc00) === 0xdc00 ? 2 : 1;
    count++;
  }
  return text.slice(0, i);
}
